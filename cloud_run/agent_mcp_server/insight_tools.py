"""Four more public tools: sponsors by age, advance risks, team notes and a one-call tour report.

Plain functions registered in main.py. Same rules as taste_tools: every request goes through
the gateway client (validation, cache, per-session budget); failures surface as RuntimeError
with a safe message; no real network access is needed to test them."""

from __future__ import annotations

import datetime as dt
import re
import time
from concurrent.futures import ThreadPoolExecutor
from urllib.parse import parse_qs, urlparse

from gateway import GatewayError, GatewayNotFound, get_json
from taste_tools import (
    _INTEGRITY, _board, _check_name, _check_place, _guarded, _resolve_artist, _stream_playbook, visible_items,
)

SITE = "https://tour-intel-qloo.web.app"
FOOTER = f"Generated by Tour Intelligence × Qloo — {SITE}"
INDEX_NOTE = "index vs the average audience; not a share of fans"
WEATHER_LABEL = "Typical weather for these dates in past years, not a forecast."
MAX_WINDOW_DAYS = 60
WS_ID = re.compile(r"[A-Za-z0-9_-]{10,64}")  # mirrors the gateway's WS_ID
_VERDICT = {"play": "Play", "hidden_goldmine": "Hidden goldmine", "de_risk": "De-risk", "consider": "Consider",
            "skip": "Skip", "insufficient_data": "Insufficient data"}
_REPORT_VERDICTS = ("play", "hidden_goldmine")


# ---------------------------------------------------------------- sponsors by age

def _brand_line(item: dict, lifted: bool) -> dict:
    out = {"name": str(item.get("name") or "")[:100], "fan_rank": item.get("artistRank")}
    if lifted and item.get("artistRank") is not None:
        city = item.get("cityRank")
        out["city_rank"] = city
        out["lift"] = (f"fans rank it #{item['artistRank']}; not in the city's top 20" if city is None
                       else f"fans rank it #{item['artistRank']}; city rank #{city}")
    else:
        out["city_rank"] = None
    return out


# Human labels matching the website; the gateway's `band` is the Qloo key, `phrase` only echoes the request (e.g. "55-64").
_BAND_LABELS = {"24_and_younger": "18–24", "25_to_29": "25–29", "30_to_34": "30–34", "35_to_44": "35–44", "45_to_54": "45–54", "55_and_older": "55+"}
_PHRASE_LABELS = {"18-24": "18–24", "25-29": "25–29", "30-34": "30–34", "35-44": "35–44", "45-54": "45–54", "55-64": "55+"}


def _band_label(b: dict):
    return _BAND_LABELS.get(b.get("band")) or _PHRASE_LABELS.get(b.get("phrase")) or b.get("phrase") or b.get("band")


@_guarded
def get_sponsors_by_age(artist: str, city: str, country: str, *, session_id: str, token_fn) -> dict:
    artist = _check_name("artist", artist)
    city, country = _check_place(city, country)
    who = _resolve_artist(artist, session_id=session_id, token_fn=token_fn)
    if "status" in who:
        return who
    data = get_json("/v1/sponsor-segments", params={"artistId": who["id"], "city": city, "country": country},
                    session_id=session_id, token_fn=token_fn)
    status = data.get("status")
    base = {"artist": who, "city": city, "country": country, "age_only": True, "integrity": _INTEGRITY}
    if status == "unavailable":
        return {"status": "unavailable", "reason": data.get("reason"), "message": str(data.get("message") or "Not available right now"), **base}
    if status == "no_skew":
        return {"status": "no_skew", "bands": [],
                "message": "No age group over-indexes enough to break sponsors out; use get_city_playbook for the all-fans list.", **base}
    bands = []
    for b in data.get("bands") or []:
        if not isinstance(b, dict):
            continue
        lifted = bool(b.get("lifted"))
        items = [i for i in b.get("items") or [] if isinstance(i, dict)][:5]
        bands.append({
            "band": _band_label(b), "index": b.get("index"), "index_note": INDEX_NOTE,
            "status": b.get("status"), "brands": [_brand_line(i, lifted) for i in items],
            "new_in_top5": b.get("newInTop5"),
            "new_in_top5_note": "brands in this age group's top 5 that are not in the all-fans top 5" if b.get("newInTop5") is not None else None,
        })
    return {"status": "ok", "bands": bands, **base}


# ---------------------------------------------------------------- advance risks

def _parse_window(start_date, end_date) -> tuple[str, str]:
    def one(label, v):
        if not isinstance(v, str) or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", v.strip()):
            raise ValueError(f"{label} must be a date as YYYY-MM-DD")
        try:
            return dt.date.fromisoformat(v.strip())
        except ValueError:
            raise ValueError(f"{label} must be a real calendar date as YYYY-MM-DD") from None
    s, e = one("start_date", start_date), one("end_date", end_date)
    if e < s:
        raise ValueError("end_date must be on or after start_date")
    if (e - s).days > MAX_WINDOW_DAYS:
        raise ValueError(f"the date window must be at most {MAX_WINDOW_DAYS} days")
    return s.isoformat(), e.isoformat()


def _web_section(sec) -> dict:
    sec = sec if isinstance(sec, dict) else {}
    if sec.get("status") != "ok":
        return {"status": sec.get("status") or "unavailable", "message": str(sec.get("message") or "Not available right now"),
                "sources": [s.get("url") for s in (sec.get("sources") or [])[:3] if isinstance(s, dict) and s.get("url")]}
    out = {"status": "ok", "summary": sec.get("summary") or "",
           "items": [{"text": i.get("text"), "source_url": i.get("sourceUrl")} for i in sec.get("items") or [] if isinstance(i, dict)]}
    if sec.get("leadTime"):
        out["lead_time"] = sec["leadTime"]
    if sec.get("artistCountry"):
        out["artist_country"] = sec["artistCountry"]
    return out


@_guarded
def get_advance_risks(city: str, country: str, start_date: str, end_date: str, artist_country: str = "", *, session_id: str, token_fn) -> dict:
    city, country = _check_place(city, country)
    start, end = _parse_window(start_date, end_date)
    params = {"city": city, "country": country, "start": start, "end": end}
    if isinstance(artist_country, str) and artist_country.strip():
        params["artistCountry"] = _check_name("artist_country", artist_country)
    data = get_json("/v1/advance", params=params, session_id=session_id, token_fn=token_fn)

    w = data.get("weather") if isinstance(data.get("weather"), dict) else {}
    if w.get("status") == "ok":
        tmax, tmin = w.get("tempMaxC") or {}, w.get("tempMinC") or {}
        weather = {
            "status": "ok", "label": WEATHER_LABEL, "years": w.get("years"),
            "typical_high_c": tmax.get("mean"), "high_range_c": [tmax.get("min"), tmax.get("max")],
            "typical_low_c": tmin.get("mean"), "rain_days_share": w.get("rainDaysShare"),
            "source_url": w.get("sourceUrl"),
        }
    else:
        weather = {"status": "unavailable", "message": str(w.get("message") or "Weather history is unavailable")}
    h = data.get("holidays") if isinstance(data.get("holidays"), dict) else {}
    if h.get("status") == "ok":
        holidays = {"status": "ok", "source_url": h.get("sourceUrl"),
                    "items": [{"date": i.get("date"), "name": i.get("name"), "near_window": bool(i.get("near"))}
                              for i in h.get("items") or [] if isinstance(i, dict)]}
    else:
        holidays = {"status": "unavailable", "message": str(h.get("message") or "Public holidays are unavailable")}
    return {
        "status": "ok", "city": city, "country": country, "window": {"start": start, "end": end},
        "weather": weather, "holidays": holidays,
        "visa": _web_section(data.get("visa")), "equipment": _web_section(data.get("equipment")),
        "note": "Visa and equipment items come from web sources checked against the cited page; confirm with the consulate or a customs broker before relying on them. Not legal advice.",
    }


# ---------------------------------------------------------------- team notes

def extract_ws_id(value) -> str:
    """A bare workspace id, or a share URL carrying it as the `ws` query (or fragment) parameter."""
    if not isinstance(value, str) or not value.strip() or len(value) > 500:
        raise ValueError("workspace_link_or_id must be a workspace share link or its id")
    v = value.strip()
    if "://" in v or "?" in v or "ws=" in v:
        u = urlparse(v if "://" in v else "https://x/" + v.lstrip("/"))
        found = (parse_qs(u.query).get("ws") or parse_qs(u.fragment).get("ws") or [None])[0]
        if not found:
            raise ValueError("no ws parameter found in that link")
        v = found
    if not WS_ID.fullmatch(v):
        raise ValueError("that does not look like a workspace id (10-64 letters, digits, - or _)")
    return v


def _who(o: dict) -> dict:
    out = {"by": o.get("name"), "role": o.get("role")}
    if o.get("demo"):
        out["marking"] = "Demo teammate"
    return out


def _msg(m: dict) -> dict:
    return {**_who(m), "text": m.get("text"), "at": m.get("at")}


@_guarded
def get_team_notes(workspace_link_or_id: str, *, session_id: str, token_fn) -> dict:
    ws = extract_ws_id(workspace_link_or_id)
    try:
        snap = get_json(f"/v1/ws/{ws}", session_id=session_id, token_fn=token_fn)
    except GatewayNotFound:
        return {"status": "not_found", "message": "Workspace not found or expired (workspaces expire after 30 days)."}
    statuses = [{"city_id": cid, "status": s.get("status"), **_who(s), "at": s.get("at")}
                for cid, s in (snap.get("statuses") or {}).items() if isinstance(s, dict)]
    open_threads, resolved = [], []
    for key, t in (snap.get("threads") or {}).items():
        if not isinstance(t, dict):
            continue
        msgs = [m for m in t.get("messages") or [] if isinstance(m, dict)]
        if t.get("resolved"):
            rb = t.get("resolvedBy") if isinstance(t.get("resolvedBy"), dict) else {}
            resolved.append({"thread": key, "resolved_by": rb.get("name"), "resolved_at": t.get("resolvedAt"),
                             "decision": _msg(msgs[-1]) if msgs else None})
        else:
            open_threads.append({"thread": key, "message_count": len(msgs), "last_messages": [_msg(m) for m in msgs[-2:]]})
    overrides = [{"city_id": cid, "field": field, "value": o.get("value"), "qloo_suggested": o.get("original") or None, **_who(o), "at": o.get("at")}
                 for cid, fields in (snap.get("overrides") or {}).items() if isinstance(fields, dict)
                 for field, o in fields.items() if isinstance(o, dict)]
    leads = [{"city_id": cid, "text": l.get("text"), **_who(l), "at": l.get("at")}
             for cid, ls in (snap.get("leads") or {}).items() if isinstance(ls, list)
             for l in ls if isinstance(l, dict)]
    activity = [{"type": e.get("type"), "city_id": e.get("cityId"), "key": e.get("key"), "text": e.get("text"), **_who(e), "at": e.get("at")}
                for e in (snap.get("activity") or [])[:10] if isinstance(e, dict)]  # snapshot is newest first
    return {
        "status": "ok", "workspace": ws, "read_only": True, "city_statuses": statuses,
        "open_threads": open_threads, "resolved_decisions": resolved, "overrides": overrides,
        "sponsor_leads": leads, "recent_activity": activity,
        "note": "Notes are written by the people on the workspace; entries marked 'Demo teammate' are seeded demo content, not real people.",
    }


# ---------------------------------------------------------------- one-call tour report

def _md(s) -> str:
    """Escape text for a markdown table/line (no pipes or newlines from upstream names)."""
    return re.sub(r"\s+", " ", str(s if s is not None else "")).replace("|", "/").strip()


def _num(v) -> str:
    return "n/a" if v is None else (str(round(v)) if isinstance(v, (int, float)) else _md(v))


def _card(cards: list, kind: str) -> dict:
    return next((c for c in cards if isinstance(c, dict) and c.get("kind") == kind), {})


def _claims_line(narrative: dict | None) -> str | None:
    """'N verified · M removed' from the narrative event, only when the gateway sent one."""
    if not isinstance(narrative, dict) or narrative.get("status") != "ok":
        return None
    cards = narrative.get("cards") if isinstance(narrative.get("cards"), dict) else {}
    ok = sum(len(c.get("verified") or []) for c in cards.values() if isinstance(c, dict))
    removed = sum(len(c.get("removed") or []) for c in cards.values() if isinstance(c, dict))
    return f"{ok} verified · {removed} removed"


def _summarise_city(cards: list, narrative: dict | None) -> dict:
    sp = _card(cards, "sponsors")
    sponsors = []
    for it in sp.get("items") or []:
        if not isinstance(it, dict) or it.get("nonSponsor") or it.get("isNonSponsor"):
            continue  # the gateway already drops organisations; also honour an explicit flag
        sponsors.append(_brand_line(it, it.get("artistRank") is not None))
        if len(sponsors) == 3:
            break
    venues = [v for v in _card(cards, "venue_fit").get("items") or [] if isinstance(v, dict) and v.get("name")]
    best = max(venues, key=lambda v: v.get("affinity") if isinstance(v.get("affinity"), (int, float)) else -1, default=None)
    co_items, hidden = visible_items("co_billing", [i for i in _card(cards, "co_billing").get("items") or [] if isinstance(i, dict)])
    act = co_items[0] if co_items else None
    zones = [z for z in _card(cards, "promo_zones").get("items") or [] if isinstance(z, dict) and (z.get("label") or z.get("name"))]
    zone = max(zones, key=lambda z: z.get("share") if isinstance(z.get("share"), (int, float)) else -1, default=None)
    out = {
        "sponsors": sponsors,
        "best_venue": {"name": best.get("name"), "affinity": best.get("affinity")} if best else None,
        "top_support_act": ({"name": act.get("name"), "shared_taste": act.get("sharedTaste"),
                             "shared_tags": act.get("sharedTags") if isinstance(act.get("sharedTags"), list) else [], "lift": act.get("lift")} if act else None),
        "top_promo_zone": {"name": zone.get("label") or zone.get("name"), "share": zone.get("share")} if zone else None,
        "hidden_acts": hidden,
    }
    claims = _claims_line(narrative)
    if claims:
        out["claims"] = claims
    return out


def _city_markdown(c: dict) -> list[str]:
    lines = [f"### {_md(c['name'])}, {_md(c['country'])} — {_VERDICT.get(c['verdict'], _md(c['verdict']))}"]
    if c.get("error"):
        return lines + [f"_Playbook unavailable: {_md(c['error'])}_", ""]
    if c["sponsors"]:
        lines.append("**Top sponsors (affinity signal)**")
        for s in c["sponsors"]:
            lines.append(f"- {_md(s['name'])}" + (f" — {_md(s['lift'])}" if s.get("lift") else ""))
    else:
        lines.append("**Top sponsors:** none listed")
    v = c["best_venue"]
    lines.append(f"- **Best venue:** {_md(v['name'])}" + (f" (taste fit {v['affinity']:.2f}, comparable only within this city)" if isinstance(v.get("affinity"), (int, float)) else "") if v else "- **Best venue:** none ranked")
    a = c["top_support_act"]
    if a:
        tags = ", ".join(_md(t) for t in a["shared_tags"][:4])
        lines.append(f"- **Top co-billing act:** {_md(a['name'])}" + (f" — shared taste: {tags}" if tags else ""))
    else:
        lines.append("- **Top co-billing act:** none listed")
    z = c["top_promo_zone"]
    lines.append(f"- **Top promo zone:** {_md(z['name'])}" + (f" ({z['share'] * 100:.0f}% of mapped fan heat)" if isinstance(z.get("share"), (int, float)) else "") if z else "- **Top promo zone:** none mapped")
    if c.get("hidden_acts"):
        n = c["hidden_acts"]
        lines.append(f"- _{n} act{'s' if n != 1 else ''} hidden by our do-not-book list_")
    if c.get("claims"):
        lines.append(f"- **Claims:** {c['claims']}")
    return lines + [""]


def build_markdown(artist: str, board: list[dict], cities: list[dict], notes: list[str], today: str) -> str:
    lines = [f"# Tour report: {_md(artist)}", f"_{today}_", "",
             f"> {_INTEGRITY} Scores are comparable within this report only.", "",
             "## Board", "", "| City | Verdict | Fan heat | Activation | Winnability |", "|---|---|---|---|---|"]
    for b in board:
        lines.append(f"| {_md(b['name'])}, {_md(b['country'])} | {_VERDICT.get(b['verdict'], _md(b['verdict']))} | "
                     f"{_num(b['fan_heat'])} | {_num(b['activation'])} | {_num(b['winnability'])} |")
    if not board:
        lines.append("| _no cities scored_ | | | | |")
    lines.append("")
    if cities:
        lines += ["## City playbooks", ""]
        for c in cities:
            lines += _city_markdown(c)
    for n in notes:
        lines.append(f"_Note: {_md(n)}_")
    lines += ["", "---", FOOTER]
    return "\n".join(lines)


@_guarded
def get_tour_report(artist: str, regions: list[str], max_stops: int = 3, *, session_id: str, token_fn,
                    max_regions: int = 2, max_cities: int = 3, workers: int = 2, today=None) -> dict:
    artist = _check_name("artist", artist)
    if not isinstance(regions, list) or not 1 <= len(regions) <= max_regions:
        raise ValueError(f"regions must have 1-{max_regions} items")
    regions = [_check_name("region", r) for r in regions]
    if not isinstance(max_stops, int) or isinstance(max_stops, bool) or not 1 <= max_stops <= 20:
        raise ValueError("max_stops must be between 1 and 20")
    max_stops = min(max_stops, max_cities)
    started = time.monotonic()
    kw = {"session_id": session_id, "token_fn": token_fn}
    who = _resolve_artist(artist, **kw)
    if "status" in who:
        return who
    board = _board(who, regions, max_stops, **kw)
    if board.get("status") == "error":
        return board
    notes: list[str] = []
    if board["status"] == "partial":
        notes.append("The market board is partial (the Qloo budget or stream stopped early).")
    scored = board["cities"]
    picks = [c for c in scored if c.get("verdict") in _REPORT_VERDICTS][:max_stops]

    def run(c: dict) -> dict:
        row = {"name": c["name"], "country": c["country"], "verdict": c["verdict"]}
        try:
            cards, narrative = _stream_playbook(who, str(c["name"]), str(c["country"]), **kw)
            return {**row, **_summarise_city(cards, narrative)}
        except (GatewayError, RuntimeError) as err:
            return {**row, "error": str(err)}

    if picks:
        # Small concurrency (2) keeps the per-IP session budget and the gateway calm; ~2 waves for 3 cities.
        with ThreadPoolExecutor(max_workers=max(1, workers)) as pool:
            cities = list(pool.map(run, picks))
    else:
        cities = []
        notes.append("No Play or hidden-goldmine markets in this board, so no city playbooks were run.")
    failed = [c["name"] for c in cities if c.get("error")]
    if failed:
        notes.append("Playbook unavailable for: " + ", ".join(str(n) for n in failed) + ". The rest of the report is complete.")
    status = "ok" if board["status"] == "ok" and not failed else "partial"
    day = today or dt.date.today().isoformat()
    return {
        "status": status, "artist": board["artist"], "generated": day, "board": scored, "cities": cities,
        "notes": notes, "qloo_requests_board": board.get("qloo_requests"), "elapsed_s": round(time.monotonic() - started, 1),
        "integrity": _INTEGRITY, "footer": FOOTER,
        "markdown": build_markdown(board["artist"]["name"], scored, cities, notes, day),
    }
