import { applyDoNotBook, isHiddenItem, visibleClaimTotals } from "../qloo/doNotBook";
import { INTEGRITY_LINE, VERDICT_LABEL } from "../qloo/labels";
import { playbookReducer, initialPlaybook, type PlaybookState } from "../qloo/playbookReducer";
import { sortCities } from "../qloo/ranking";
import type { Showcase } from "../qloo/showcase";
import { zoneDisplayLabel } from "../qloo/zones";
import type { PlaybookCard, ScoredCity } from "../qloo/types";

/** The public MCP's get_tour_report returns this shape of markdown. The page builds an example of it from the recorded run, so nothing is typed in by hand. */
export const REPORT_FOOTER = "Generated by Tour Intelligence × Qloo — https://tour-intel-qloo.web.app";
const BOARD_ROWS = 8;

const md = (s: unknown): string => String(s).replace(/[|\r\n]+/g, " ").trim();
const num = (v: number | null): string => (v === null ? "n/a" : String(Math.round(v)));
const text = (it: Record<string, unknown> | undefined, ...keys: string[]): string | null => {
  for (const k of keys) { const v = it?.[k]; if (typeof v === "string" && v) return v; }
  return null;
};
const shown = (card: PlaybookCard | undefined) => (card && card.status === "ok" ? applyDoNotBook(card).card.items : []);

function playbookOf(show: Showcase, id: string): PlaybookState | null {
  const events = show.playbooks[id];
  if (!events) return null;
  return events.reduce<PlaybookState>((s, event) => playbookReducer(s, { type: "event", event }), initialPlaybook);
}

/** The city the example walks through: Los Angeles when the recording has it, else the best-scoring Play or Hidden goldmine city with a playbook. */
function featured(show: Showcase, cities: ScoredCity[]): ScoredCity | null {
  const withBook = cities.filter((c) => show.playbooks[c.id]);
  return withBook.find((c) => /^los angeles$/i.test(c.name)) ?? withBook.find((c) => c.verdict === "play" || c.verdict === "hidden_goldmine") ?? withBook[0] ?? null;
}

function cityLines(show: Showcase, city: ScoredCity): string[] {
  const pb = playbookOf(show, city.id);
  const lines = [`### ${md(city.name)}, ${md(city.country)} — ${VERDICT_LABEL[city.verdict]}`];
  if (!pb) return [...lines, "_Playbook unavailable_", ""];
  const card = (kind: PlaybookCard["kind"]) => pb.cards.find((c) => c.kind === kind);
  const sponsors = shown(card("sponsors")).slice(0, 3);
  if (sponsors.length) {
    lines.push("**Top sponsors (affinity signal)**");
    for (const s of sponsors) lines.push(`- ${md(text(s, "name") ?? "")}`);
  } else lines.push("**Top sponsors:** none listed");
  const venues = shown(card("venue_fit")).filter((v) => text(v, "name"));
  const best = venues.reduce<Record<string, unknown> | undefined>((a, v) => (typeof v.affinity === "number" && (a === undefined || v.affinity > (a.affinity as number)) ? v : a), venues[0]);
  lines.push(best ? `- **Best venue:** ${md(text(best, "name"))}${typeof best.affinity === "number" ? ` (taste fit ${best.affinity.toFixed(2)}, comparable only within this city)` : ""}` : "- **Best venue:** none ranked");
  const act = shown(card("co_billing")).find((i) => !isHiddenItem("co_billing", i) && text(i, "name"));
  lines.push(act ? `- **Top co-billing act:** ${md(text(act, "name"))}` : "- **Top co-billing act:** none listed");
  const zone = shown(card("promo_zones")).find((z) => text(z, "label", "name"));
  const share = zone?.share;
  lines.push(zone ? `- **Top promo zone:** ${md(zoneDisplayLabel(text(zone, "label", "name")!, city.name))}${typeof share === "number" ? ` (${Math.round(share * 100)}% of mapped fan heat)` : ""}` : "- **Top promo zone:** none mapped");
  if (pb.narrative?.status === "ok") {
    const { verified, removed } = visibleClaimTotals(pb.narrative.cards);
    lines.push(`- **Claims:** ${verified} verified · ${removed} removed`);
  }
  return [...lines, ""];
}

export interface ExampleReport { markdown: string; label: string }

/** Markdown in the shape get_tour_report returns, built from a recorded run. Do-not-book acts and non-sponsor organisations are filtered as in the app. */
export function buildExampleReport(show: Showcase): ExampleReport {
  const cities = sortCities(show.boardEvents.flatMap((e) => (e.type === "city_scored" ? [e.city] : [])), "winnability");
  const day = show.recordedAt ? new Date(show.recordedAt) : null;
  const when = day && !Number.isNaN(day.getTime()) ? day.toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" }) : null;
  const label = show.recordedAt && when ? `Example output, built from the recorded ${show.artist} run (${when})` : `Example output, built from the sample ${show.artist} run`;
  const lines = [
    `# Tour report: ${md(show.artist)}`, when ? `_${day!.toISOString().slice(0, 10)}_` : "_Sample run_", "",
    `> ${INTEGRITY_LINE} Scores are comparable within this report only.`, "",
    "## Board", "", "| City | Verdict | Fan heat | Activation | Winnability |", "|---|---|---|---|---|",
    ...cities.slice(0, BOARD_ROWS).map((c) => `| ${md(c.name)}, ${md(c.country)} | ${VERDICT_LABEL[c.verdict]} | ${num(c.fanHeat.value)} | ${num(c.activation.value)} | ${num(c.winnability.value)} |`),
    ...(cities.length ? [] : ["| _no cities scored_ | | | | |"]),
    "",
  ];
  const pick = featured(show, cities);
  if (pick) lines.push("## City playbooks", "", ...cityLines(show, pick));
  lines.push("---", REPORT_FOOTER);
  return { markdown: lines.join("\n"), label };
}
